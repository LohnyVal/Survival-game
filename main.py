def build_wall(grid):
    walls = []
    for row, line in enumerate(grid):
        for col, cell in enumerate(line):
            if cell == 1:
                walls.append((col * TILE, row * TILE, TILE, TILE))
    return walls

class Player:
    def __init__(self, name, health, damage, x, y, left, right, up, down):
        self.name = name
        self.health = health
        self.damage = damage
        self.x_pos = x
        self.y_pos = y
        self.left = left
        self.right = right
        self.up = up
        self.down = down

    def get_rect(self):
        return pygame.Rect(self.x_pos, self.y_pos, PLAYER_SIZE, PLAYER_SIZE)

def main():
    running = True

    walls = build_wall(MAP)

    while running:
        clock.tick(FPS)
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
            if event.type == pygame.KEYDOWN:
                if event.key == pygame.K_ESCAPE:
                    running = False


        WIN.fill(BG)

        for wall in walls:
            pygame.draw.rect(WIN, BLUE, wall)

        pygame.display.update()
    pygame.quit()


if __name__ == "__main__":
    main()